"""A2A seller agent for the FICTITIOUS listing velo-test-001 (rule-based, no LLM).
Started by watchdog.sh exactly like the old echo server (same path, port 127.0.0.1:9999).
Negotiation logic: negotiation.py. State: negotiations.db. Private thresholds: private_config.json."""
import os
from urllib.parse import urlparse
import uvicorn
from starlette.applications import Starlette
from starlette.responses import JSONResponse
from starlette.routing import Route
from a2a.server.agent_execution import AgentExecutor, RequestContext
from a2a.server.events import EventQueue
from a2a.server.request_handlers import DefaultRequestHandler
from a2a.server.tasks import InMemoryTaskStore
from a2a.server.routes import create_agent_card_routes, create_jsonrpc_routes
from a2a.types import AgentCard, AgentSkill, AgentCapabilities, AgentInterface
from a2a.helpers.proto_helpers import new_text_message
import negotiation

def _base():
    b = os.environ.get("PUBLIC_BASE_URL")
    if not b:
        try: b = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "public_base_url.txt")).read().strip()
        except OSError: b = ""
    return (b or "http://localhost:9999").rstrip("/")
BASE = _base()
HOST = urlparse(BASE).netloc

class SellerExecutor(AgentExecutor):
    async def execute(self, context: RequestContext, event_queue: EventQueue):
        cid = context.context_id  # generated by the SDK if the client sent none; echoed back below
        try:
            reply = negotiation.handle(cid, context.get_user_input() or "")
        except Exception:
            reply = "Désolé, une erreur interne est survenue. Réessaie avec une question ou une proposition de prix."
        await event_queue.enqueue_event(new_text_message(reply, context_id=cid))
    async def cancel(self, context, event_queue):
        raise Exception("cancel not supported")

PUBLIC = ("Annonce FICTIVE de test velo-test-001 : vélo de ville adulte, cadre taille M, 7 vitesses, bon état général, "
          "rayures sur le cadre, éclairage avant à remplacer. Prix affiché : 180 EUR. Remise en main propre à Lyon, "
          "samedi après-midi. Aucun paiement, aucune réservation réelle, aucune expédition.")
card = AgentCard(
    name="Velo-test-001 - Vendeur (annonce fictive de test)",
    description=PUBLIC + " Cet agent permet de consulter l'annonce et d'en négocier le prix. Toute proposition doit être "
                "confirmée explicitement par le vendeur et reste un accord fictif. Le contextId identifie la négociation.",
    version="2.0.0",
    supported_interfaces=[AgentInterface(url=BASE + "/", protocol_binding="JSONRPC", protocol_version="1.0")],
    capabilities=AgentCapabilities(streaming=False, push_notifications=False),
    default_input_modes=["text/plain"], default_output_modes=["text/plain"],
    skills=[
        AgentSkill(id="consult-annonce", name="Consultation de l'annonce velo-test-001",
                   description="Répond aux questions sur l'annonce fictive velo-test-001 uniquement à partir des caractéristiques "
                               "publiées. Si une information manque, l'agent l'indique sans l'inventer.",
                   tags=["annonce", "vélo", "occasion", "consultation", "fictif", "test"],
                   examples=["Quelle est la taille du cadre ?", "Combien de vitesses ?", "Où se fait la remise ?"],
                   input_modes=["text/plain"], output_modes=["text/plain"]),
        AgentSkill(id="negotiate-annonce", name="Négociation du prix de l'annonce fictive velo-test-001",
                   description="Négociation du prix de l'annonce fictive (prix affiché 180 EUR). Aucun paiement, aucune réservation, "
                               "aucune expédition. Toute proposition est soumise à la confirmation explicite du vendeur ; "
                               "l'accord est fictif. Envoie « statut » dans la même négociation (même contextId) pour connaître la décision.",
                   tags=["négociation", "prix", "vélo", "occasion", "fictif", "test"],
                   examples=["Je propose 170 EUR", "J'accepte les conditions", "statut"],
                   input_modes=["text/plain"], output_modes=["text/plain"]),
    ],
)

CATALOG = {
    "specVersion": "1.0",
    "host": {"displayName": "Hôte A2A de test (annonce fictive)", "identifier": HOST},
    "entries": [{
        "identifier": f"urn:air:{HOST}:a2a:velo-test-001",
        "displayName": "Velo-test-001 - Vendeur (annonce fictive de test)",
        "type": "application/a2a-agent-card+json",
        "url": BASE + "/.well-known/agent-card.json",
        "version": "2.0.0",
        "description": "Agent vendeur A2A pour une annonce fictive de test (velo-test-001) : consultation et négociation, "
                       "prix affiché 180 EUR, remise en main propre à Lyon le samedi après-midi, aucun paiement, réservation "
                       "ni expédition, confirmation du vendeur requise. JSON-RPC sur /.",
        "tags": ["a2a", "annonce", "fictif", "test", "vélo", "négociation", "consultation"],
    }],
}
async def catalog(_):
    return JSONResponse(CATALOG, media_type="application/ai-catalog+json")

handler = DefaultRequestHandler(agent_executor=SellerExecutor(), task_store=InMemoryTaskStore(), agent_card=card)
routes = create_agent_card_routes(card) + create_jsonrpc_routes(handler, rpc_url="/") + [
    Route("/.well-known/ai-catalog.json", catalog), Route("/.well-known/ard.json", catalog)]
app = Starlette(routes=routes)

if __name__ == "__main__":
    uvicorn.run(app, host="127.0.0.1", port=9999, log_level="warning")
